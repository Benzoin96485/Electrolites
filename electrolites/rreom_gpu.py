"""Rank-reduced CCSD, Λ and singlet EOM-EE-CCSD on the GPU (TeraChem's
RR-CCSD / RR-EOM-CCSD: Parrish et al., JCP 150, 164118 (2019); Hohenstein
et al., JCP 151, 164121 (2019); Hohenstein and Martinez, JCP 155, 184110
(2021)).

Every doubles quantity is held in a compressed hole-particle space,

    t2[i,j,a,b] = sum_PQ U[ia,P] T[P,Q] U[jb,Q]           (same for r2, and
    for the left/Λ doubles in the biorthonormal (Koch) convention),

with U (ov x N) orthonormal; the singles are not compressed.  The working
equations are the canonical ones projected on U (x) U, so the residuals and
sigma vectors are the existing full-rank GPU kernels (``fastccsd``,
``eom_gpu._ee_sigma``, ``ccsd_lambda_gpu.lambda_linear``) applied to the
reconstructed doubles and projected back:

    Omega_c = U^T Omega(t1, U T U^T) U.

U is rotated once so that U^T diag(e_a - e_i) U is diagonal (a_P): the
Lyapunov update of the papers, A dT + dT A = -Omega_c, is then the
diagonal division dT[P,Q] = -Omega_c[P,Q] / (a_P + a_Q).

Projectors (TeraChem's defaults in parentheses):

* ground state: eigenvectors of the MP2 doubles as an (ov x ov) matrix,
  |eigenvalue| > ``thresh`` (1e-4), from Cholesky-reduced (ia|jb)
  (``int_thresh`` 1e-2) and a Cholesky-decomposed denominator
  (``den_thresh`` 1e-2): G = -Z Z^T, Z[ia, wK] = tau[ia, w] L[ia, K];
* excited state n: eigenvectors of the CC2-like doubles generated by the
  singles r1 and the excitation energy w (paper II eq. 33, 37),
  G[ia,jb] = <ab_ij|[H, R1]|0> / (e_i + e_j - e_a - e_b + w);
* state-averaged: eigenvectors of the summed state-specific projectors,
  sum_n U_n U_n^T, with eigenvalue > ``union_thresh`` (1e-2).

Excited states follow TeraChem's scheme: one state at a time with its own
projector, rebuilt from its singles until the energy is stationary
(previous states deflated), then all states together in the union space
(right and left), and the transition properties from the reconstructed
vectors (``eom_gpu.transition_properties``).

    from electrolites import rreom_gpu
    res = rreom_gpu.run(mycc, nroots=5)        # mycc: GPU4PySCF CCSD object
"""
import time

import numpy as np
import cupy as cp
from pyscf.lib import logger

_ein = cp.einsum


# ------------------------------------------------------------------ layout
def to_mat(x2):
    """(..., o, o, v, v) -> (..., ov, ov) with M[ia, jb] = x2[i, j, a, b]."""
    *b, no, _, nv, _ = x2.shape
    nb = len(b)
    perm = tuple(range(nb)) + (nb, nb + 2, nb + 1, nb + 3)
    return x2.transpose(perm).reshape(*b, no * nv, no * nv)


def to_t2(m, no, nv):
    """inverse of ``to_mat``."""
    *b, _, _ = m.shape
    nb = len(b)
    perm = tuple(range(nb)) + (nb, nb + 2, nb + 1, nb + 3)
    return cp.ascontiguousarray(m.reshape(*b, no, nv, no, nv).transpose(perm))


def _ichunks(no, per_i, frac=.05):
    from electrolites.fastccsd import _avail
    step = max(1, min(no, int(frac * _avail() // max(per_i, 1))))
    return [(i0, min(no, i0 + step)) for i0 in range(0, no, step)]


def expand(U, R, no, nv):
    """doubles from compressed: (n, N, N) -> (n, o, o, v, v), written
    occupied block by block (no (ov x ov) intermediate and no transposed
    copy: at o 66, v 288 each is 2.9 GB)."""
    n, N = R.shape[0], U.shape[1]
    out = cp.empty((n, no, no, nv, nv))
    U3 = U.reshape(no, nv, N)
    for k in range(n):
        W = (R[k] @ U.T).reshape(N, no, nv)            # (N, j, b)
        for i0, i1 in _ichunks(no, nv * no * nv * 8 * 2):
            # x[i,a,j,b] = sum_P U[i,a,P] W[P,j,b]
            x = (U3[i0:i1].reshape(-1, N) @ W.reshape(N, -1)).reshape(
                i1 - i0, nv, no, nv)
            out[k, i0:i1] = x.transpose(0, 2, 1, 3)
            x = None
        W = None
    return out


def project(U, x2):
    """compressed from doubles: (n, o, o, v, v) -> (n, N, N), occupied
    block by block (no transposed copy of the doubles)."""
    n, no, _, nv, _ = x2.shape
    N = U.shape[1]
    U3 = U.reshape(no, nv, N)
    out = cp.empty((n, N, N))
    for k in range(n):
        Y = cp.empty((no, nv, N))                       # sum_jb x[ia,jb] U[jb]
        for i0, i1 in _ichunks(no, no * nv * nv * 8 * 2):
            xi = x2[k, i0:i1].transpose(0, 2, 1, 3).reshape(-1, no * nv)
            Y[i0:i1] = (xi @ U).reshape(i1 - i0, nv, N)
            xi = None
        out[k] = U.T @ Y.reshape(no * nv, N)
        Y = None
    return out


def g_inv(x2):
    """Λ-like (PySCF) doubles from biorthonormal ones: G^-1 X with
    G l = 2 l - l[..., b, a] (the pairing <L|R> = 2 l1.r1 + (G l2).r2)."""
    return (2 * x2 + x2.swapaxes(-1, -2)) / 3


def g_fwd(x2):
    return 2 * x2 - x2.swapaxes(-1, -2)


class Space:
    """A compressed doubles space: U (ov x N, orthonormal columns, rotated
    so that U^T diag(e_a - e_i) U = diag(a)) and its vector layout
    [r1 (ov) | lower triangle of R (N(N+1)/2)]."""

    def __init__(self, U, dvo, no, nv):
        A = U.T @ (dvo[:, None] * U)
        a, Q = cp.linalg.eigh((A + A.T) * .5)
        self.U = cp.ascontiguousarray(U @ Q)
        self.a = a
        self.no, self.nv = no, nv
        self.N = N = U.shape[1]
        self.ov = no * nv
        self.ntri = N * (N + 1) // 2
        self.dim = self.ov + self.ntri
        self.tri = cp.tril_indices(N)

    @classmethod
    def from_rotated(cls, U, a, no, nv):
        """A space from an already rotated U and its a (checkpoints)."""
        sp = cls.__new__(cls)
        sp.U, sp.a = cp.asarray(U), cp.asarray(a)
        sp.no, sp.nv, sp.N = no, nv, sp.U.shape[1]
        sp.ov = no * nv
        sp.ntri = sp.N * (sp.N + 1) // 2
        sp.dim = sp.ov + sp.ntri
        sp.tri = cp.tril_indices(sp.N)
        return sp

    def pack(self, r1, R):
        n = len(r1)
        out = cp.empty((n, self.dim))
        out[:, :self.ov] = r1.reshape(n, -1)
        out[:, self.ov:] = R[:, self.tri[0], self.tri[1]]
        return out

    def unpack(self, v):
        n = len(v)
        N = self.N
        r1 = v[:, :self.ov].reshape(n, self.no, self.nv)
        R = cp.zeros((n, N, N))
        R[:, self.tri[0], self.tri[1]] = v[:, self.ov:]
        R[:, self.tri[1], self.tri[0]] = v[:, self.ov:]
        return r1, R

    def dd(self):
        return self.a[:, None] + self.a[None, :]


# ------------------------------------------------------------------ factors
def _pivoted_cd(diag, col, thresh, maxrank=None):
    """Pivoted Cholesky of a PSD matrix given its diagonal and a column
    function: returns the list of pivots and L (n x K) with M ~ L L^T,
    stopping when the largest remaining diagonal < thresh."""
    d = diag.copy()
    n = len(d)
    maxrank = maxrank or n
    cols = []
    piv = []
    L = cp.zeros((n, min(maxrank, 4096)))
    for k in range(maxrank):
        p = int(cp.argmax(d))
        dp = float(d[p])
        if dp < thresh:
            break
        c = col(p)
        if k:
            c -= L[:, :k] @ L[p, :k]
        c /= dp ** .5
        if k == L.shape[1]:
            L = cp.concatenate([L, cp.zeros_like(L)], axis=1)
        L[:, k] = c
        d -= c * c
        d[p] = 0
        piv.append(p)
        cols.append(k)
    return piv, L[:, :len(piv)]


class Factors:
    """DF three-index integrals of the active orbitals and their pivoted
    Cholesky reduction over ov pairs (TeraChem's 'Cholesky integral
    threshold'): (pq|ia) ~ sum_K L[pq,K] L[ia,K] for pq in ov, oo, vv."""

    def __init__(self, mycc, auxbasis=None, int_thresh=1e-2, int_basis='ao'):
        from electrolites.casscf_gpu import GPUDF
        from electrolites.ccsd_t import _fock_mo
        no = mycc.nocc
        mask = mycc.get_frozen_mask()
        mo = cp.asarray(mycc.mo_coeff)[:, cp.asarray(mask)]
        nv = mo.shape[1] - no
        orbo, orbv = mo[:, :no], mo[:, no:]
        if auxbasis is None:
            from pyscf import df
            auxbasis = df.make_auxbasis(mycc.mol, mp2fit=True)
        dfo = GPUDF(mycc.mol, auxbasis)
        self.dfo = dfo
        self.orbv = orbv
        f = _fock_mo(mycc, mo)
        e = cp.diag(f)
        self.eo, self.ev = e[:no], e[no:]
        self.no, self.nv = no, nv
        self.dvo = (self.ev[None, :] - self.eo[:, None]).ravel()
        if int_basis == 'ao':
            # TeraChem: pivoted Cholesky of the AO integrals, truncated
            # where the largest remaining diagonal falls below int_thresh
            lao = dfo._ao_cderi()
            if lao is None:
                eye = cp.eye(mycc.mol.nao)
                lao = dfo._lmo_int(eye, eye)
            nao = lao.shape[0]
            self.naux = lao.shape[2]
            tri = cp.tril_indices(nao)
            Bp = lao[tri[0], tri[1]]                       # (npair, naux)
            lao = None
            diag = cp.sum(Bp * Bp, axis=1)
            piv, Lp = _pivoted_cd(diag, lambda p: Bp @ Bp[p], int_thresh)
            Bp = None
            K = Lp.shape[1]
            Lao = cp.zeros((nao, nao, K))
            Lao[tri[0], tri[1]] = Lp
            Lao[tri[1], tri[0]] = Lp
            Lp = None
            def tr(c1, c2):
                x = _ein('mnk,mp->pnk', Lao, c1)
                return _ein('pnk,nq->pqk', x, c2).reshape(-1, K)
            self.Lov, self.Loo, self.Lvv = tr(orbo, orbv), tr(orbo, orbo), \
                tr(orbv, orbv)
            Lao = None
            self.K = K
            self.Bov = dfo.lmo(orbo, orbv).reshape(no * nv, -1)
            dfo._lao = None
            return
        Bov = dfo.lmo(orbo, orbv).reshape(no * nv, -1)
        Boo = dfo.lmo(orbo, orbo).reshape(no * no, -1)
        Bvv = dfo.lmo(orbv, orbv).reshape(nv * nv, -1)
        self.naux = Bov.shape[1]
        diag = cp.sum(Bov * Bov, axis=1)
        piv, L = _pivoted_cd(diag, lambda p: Bov @ Bov[p], int_thresh)
        P = Bov[cp.asarray(piv, dtype=cp.int64)]       # (K, naux) pivot rows
        # (pq|piv) for oo, vv by the same recursion: L_x = (B_x P^T) Linv^T
        # with L[piv] lower triangular (L[piv] L[piv]^T = P P^T)
        Lp = L[cp.asarray(piv, dtype=cp.int64)]
        import cupyx.scipy.linalg as cpl
        self.Lov = L
        self.Loo = cpl.solve_triangular(Lp, (Boo @ P.T).T, lower=True).T
        self.Lvv = cpl.solve_triangular(Lp, (Bvv @ P.T).T, lower=True).T
        self.K = L.shape[1]
        self.Bov = Bov
        dfo = Boo = Bvv = None


def df_vv(F):
    """DF factors of (ae|bf) over all auxiliary functions: (v, v, naux)."""
    out = F.dfo.lmo(F.orbv, F.orbv)
    F.dfo._lao = None
    return out


def _offload(self):
    for k in ('Lov', 'Loo', 'Lvv', 'Bov'):
        x = getattr(self, k, None)
        if isinstance(x, cp.ndarray):
            setattr(self, k, cp.asnumpy(x))


def _onload(self):
    for k in ('Lov', 'Loo', 'Lvv', 'Bov'):
        x = getattr(self, k, None)
        if isinstance(x, np.ndarray):
            setattr(self, k, cp.asarray(x))


Factors.offload = _offload
Factors.onload = _onload


def _denominator_cd(x, thresh):
    """1/(x_ia + x_jb) ~ sum_w tau[ia,w] tau[jb,w] (x > 0), pivoted CD."""
    return _pivoted_cd(.5 / x, lambda p: 1. / (x + x[p]), thresh)[1]


def _proj_from_Z(Y, Zt, thresh, sym_from_Y=True):
    """Eigenvectors of the symmetric G = -Y Zt^T (ov x ov, rank <= cols)
    with |eigenvalue| > thresh, in a basis of range(Y)."""
    u, s, _ = cp.linalg.svd(Y, full_matrices=False)
    Q = u[:, s > s[0] * 1e-12]
    Gs = -(Q.T @ Y) @ (Zt.T @ Q)
    g, V = cp.linalg.eigh((Gs + Gs.T) * .5)
    keep = abs(g) > thresh
    return Q @ V[:, keep], g[keep]


def ground_projector(F, thresh=1e-4, den_thresh=1e-2):
    """MP2 projector: G = -(ia|jb)/(D_ia + D_jb) ~ -Z Z^T."""
    tau = _denominator_cd(F.dvo, den_thresh)
    Z = (tau[:, :, None] * F.Lov[:, None, :]).reshape(len(F.dvo), -1)
    u, s, _ = cp.linalg.svd(Z, full_matrices=False)
    keep = s * s > thresh
    return u[:, keep], -(s[keep] ** 2)


def state_projector(F, r1, w, thresh=1e-4, den_thresh=1e-2):
    """Paper II eq. (33)/(37): G = (L R~^T + R~ L^T)/(e_i+e_j-e_a-e_b+w),
    R~[ia,K] = sum_b r[i,b] L[ba,K] - sum_j r[j,a] L[ij,K]."""
    no, nv, K = F.no, F.nv, F.K
    r1 = cp.asarray(r1).reshape(no, nv)
    Rt = (_ein('ib,bak->iak', r1, F.Lvv.reshape(nv, nv, K))
          - _ein('ja,ijk->iak', r1, F.Loo.reshape(no, no, K))).reshape(-1, K)
    x = F.dvo - .5 * w
    assert float(x.min()) > 0, 'excitation energy above twice the gap'
    tau = _denominator_cd(x, den_thresh)
    LR = cp.concatenate([F.Lov, Rt], axis=1)
    RL = cp.concatenate([Rt, F.Lov], axis=1)
    Y = (tau[:, :, None] * LR[:, None, :]).reshape(len(x), -1)
    Zt = (tau[:, :, None] * RL[:, None, :]).reshape(len(x), -1)
    # 1/(e_i+e_j-e_a-e_b+w) = -1/(x_ia + x_jb): G = -Y Zt^T
    return _proj_from_Z(Y, Zt, thresh)


def union_projector(Us, thresh=1e-2):
    """Eigenvectors of sum_n U_n U_n^T with eigenvalue > thresh (the
    rule that reproduces TeraChem's state-averaged ranks)."""
    M = cp.concatenate(Us, axis=1)
    u, s, _ = cp.linalg.svd(M, full_matrices=False)
    return u[:, s * s > thresh], s * s


# ------------------------------------------------------------------ RR-CCSD
def rr_ccsd(mycc, sp, eris=None, max_cycle=50, tol=1e-8, tolnormt=1e-6,
            log=None):
    """Solve the compressed CCSD equations in ``sp``; sets mycc.t1, t2
    (full, reconstructed), mycc.e_corr; returns (conv, e_corr, t1, T)."""
    from electrolites import fastccsd as FC
    from gpu4pyscf.lib.diis import DIIS
    log = log or logger.new_logger(mycc)
    no, nv = sp.no, sp.nv
    FC._stack0()
    if eris is None:
        eris = FC._make_eris(mycc)
    E = FC._DevERIs(eris, no)
    eia = E.mo_energy[:no, None] - E.mo_energy[None, no:]
    t1 = E.fock[:no, no:] / eia
    t2 = (E.ovov.transpose(0, 2, 1, 3) /
          (eia[:, None, :, None] + eia[None, :, None, :]))
    T = project(sp.U, t2[None])[0]
    dd = sp.dd()
    adiis = DIIS(mycc, incore=True)
    adiis.space = mycc.diis_space
    e_old = 0.
    t2 = expand(sp.U, T[None], no, nv)[0]
    ecc = FC.energy(t1, t2, E)
    conv = False
    for it in range(max_cycle):
        t1n, t2n = FC.update_amps(mycc, t1, t2, E)
        t2n -= t2
        for i in range(no):                    # residual = D (t2new - t2)
            t2n[i] *= eia[i][None, :, None] + eia[:, None, :]
        oc = project(sp.U, t2n[None])[0]
        t2n = None
        dT = -oc / dd
        dT = (dT + dT.T) * .5
        normt = float(cp.sqrt(cp.sum((t1n - t1) ** 2) + cp.sum(dT * dT)))
        vec = adiis.update(cp.concatenate([t1n.ravel(), (T + dT).ravel()]))
        t1 = vec[:no * nv].reshape(no, nv).copy()
        T = vec[no * nv:].reshape(sp.N, sp.N).copy()
        t2 = None
        t2 = expand(sp.U, T[None], no, nv)[0]
        e_old, ecc = ecc, FC.energy(t1, t2, E)
        log.info('RR-CCSD cycle %d  E_corr %.12f  dE %.3e  norm(dt1,dT) %.3e',
                 it + 1, ecc, ecc - e_old, normt)
        if abs(ecc - e_old) < tol and normt < tolnormt:
            conv = True
            break
    mycc.t1, mycc.t2, mycc.e_corr = t1, t2, ecc
    mycc.converged = conv
    # the AO integral blocks fastccsd cached on the device (as its kernel)
    mycc._fastccsd_vhfopt = mycc._fastccsd_eri = None
    mycc._fastccsd_nocache = False
    E = eris = None
    cp.get_default_memory_pool().free_all_blocks()
    return conv, ecc, t1, T


def rr_lambda(mycc, sp, max_cycle=50, tol=1e-6, log=None, Bvv=None):
    """Compressed Λ equations (λ2 in the biorthonormal convention is
    U Λ U^T); sets mycc.l1, l2 (PySCF convention, full).  With ``Bvv`` the
    ladder is factorised (``DFLadder``)."""
    from electrolites import ccsd_lambda_gpu as LG
    from electrolites.eom_gpu import _Imds
    from gpu4pyscf.lib.diis import DIIS
    log = log or logger.new_logger(mycc)
    no, nv = sp.no, sp.nv
    imds = LG.make_intermediates(_Imds(mycc))
    c1, c2 = LG._lambda_const(imds, mycc)
    d1 = LG._lambda_diag(imds, mycc)
    dd = sp.dd()
    if callable(Bvv):          # built after the intermediates (peak memory)
        Bvv = Bvv()
    lad = DFLadder(Bvv, sp, imds.t1, log) if Bvv is not None else None
    l1 = imds.t1.copy()
    Lc = project(sp.U, g_fwd(imds.t2)[None])[0]
    adiis = DIIS(mycc, incore=True)
    adiis.space = getattr(mycc, 'diis_space', 6)
    conv = False
    for it in range(max_cycle):
        l2 = g_inv(expand(sp.U, Lc[None], no, nv))
        s1, s2 = LG.lambda_linear(
            imds, mycc, l1[None], l2, ladder_l1=None if lad is None else
            (lambda L2: lad.l1_part(L2, imds.t1)))
        s1 = s1[0] + c1
        rc = project(sp.U, g_fwd(s2 + c2[None]))[0]
        if lad is not None:
            rc += lad.project(Lc[None])[0]
        s2 = l2 = None
        dl1 = s1 / d1
        dL = -rc / dd
        dL = (dL + dL.T) * .5
        normt = float(cp.sqrt(cp.sum(dl1 ** 2) + cp.sum(dL * dL)))
        vec = adiis.update(cp.concatenate([(l1 + dl1).ravel(),
                                           (Lc + dL).ravel()]))
        l1 = vec[:no * nv].reshape(no, nv).copy()
        Lc = vec[no * nv:].reshape(sp.N, sp.N).copy()
        log.info('RR-lambda cycle %d  norm %.3e', it + 1, normt)
        if normt < tol:
            conv = True
            break
    mycc.l1 = l1
    mycc.l2 = g_inv(expand(sp.U, Lc[None], no, nv))[0]
    return conv, l1, Lc


# ------------------------------------------------------------------ EOM
def dressed_vv(Bvv, Bov, t1):
    """T1-dressed DF factors B^[a,e,A] = B[a,e,A] - sum_m t1[m,a] B[m,e,A]
    (the particle index of the T1-transformed (ae|bf))."""
    no, nv = t1.shape
    Bo = cp.asarray(Bov).reshape(no, nv, -1)
    return Bvv - _ein('ma,meA->aeA', cp.asarray(t1), Bo)


class DFLadder:
    """The particle-particle ladder sum_ef (ae|bf) x[ij,ef] with DF
    integrals (ae|bf) = sum_A B[a,e,A] B[b,f,A] (all auxiliary functions),
    for compressed doubles: for x = U R U^T its projection is

        U^T Lad(x) U = sum_A y_A R y_A^T,   y_A = sum_i U_i^T B_A U_i,

    (U_i: the (v x N) rows of U for occupied i), and for the rank-one
    pieces r1 t1 + t1 r1 of tau2 it is (U^T rho)(U^T theta)^T + t.,
    rho[ia,A] = sum_e B[a,e,A] r[i,e].  With the bare B, y_A is symmetric;
    with the T1-dressed B^ (``dressed_vv``) the same formulas give the
    T1-transformed ladder sum_ef (ae^|bf^) x[ij,ef], which also carries the
    -t1 (me|bf) and t1 t1 (me|nf) terms of the sigma (``dressed=True``;
    the left operator takes the transpose, sum_A y_A^T L y_A).  y
    (naux N^2) is built once per projector, on the device if it fits,
    else in pinned host memory and streamed per call."""

    def __init__(self, Bvv, sp, t1, log=None, dev_frac=.25, dressed=False):
        from electrolites.fastccsd import _avail
        no, nv, N = sp.no, sp.nv, sp.N
        naux = Bvv.shape[2]
        self.sp, self.naux = sp, naux
        self.dressed = dressed
        self.Bvv = Bvv
        self.theta = _ein('bfA,jf->jbA', Bvv, t1).reshape(no * nv, naux)
        self.Ut = sp.U.T @ self.theta                    # (N, naux)
        U3 = sp.U.reshape(no, nv, N)
        nbytes = naux * N * N * 8
        self.on_dev = nbytes < dev_frac * _avail()
        if self.on_dev:
            self.y = cp.empty((naux, N, N))
        else:
            self.y = cupyx_empty_pinned((naux, N, N))
        # block of auxiliary functions: (nb, o, v, N) temporaries
        nb = max(1, min(naux, int(.08 * _avail() // (no * nv * N * 8 * 2))))
        t0 = time.perf_counter()
        for a0 in range(0, naux, nb):
            a1 = min(naux, a0 + nb)
            Bb = cp.ascontiguousarray(Bvv[:, :, a0:a1].transpose(2, 0, 1))
            # X[A, i, a, R] = sum_e B_A[a, e] U[i, e, R]
            X = cp.matmul(Bb[:, None], U3[None])          # (nb, o, v, N)
            Yb = cp.matmul(sp.U.T[None], X.reshape(a1 - a0, no * nv, N))
            X = None
            if self.on_dev:
                self.y[a0:a1] = Yb
            else:
                Yb.get(out=self.y[a0:a1])
            Yb = None
        self.nb = nb
        cp.cuda.Device().synchronize()
        if log:
            log.info('RR ladder: y %.1f GB on %s, built in %.1f s',
                     nbytes / 1e9, 'device' if self.on_dev else 'host',
                     time.perf_counter() - t0)

    def project(self, R, r1=None, trans=False):
        """U^T Lad(U R U^T + r1 t1 + t1 r1) U for R (n, N, N); ``trans``:
        the transposed ladder (left operator, no r1)."""
        n, N = len(R), self.sp.N
        out = cp.zeros_like(R)
        nb = max(1, min(self.naux, int(1e9 // (N * N * 8))))
        for a0 in range(0, self.naux, nb):
            a1 = min(self.naux, a0 + nb)
            y = self.y[a0:a1] if self.on_dev else cp.asarray(self.y[a0:a1])
            yt = y.transpose(0, 2, 1)
            if trans:
                y, yt = yt, y
            for k in range(n):
                T = cp.matmul(y, R[k])                       # (nb, N, N)
                out[k] += cp.matmul(T, yt).sum(axis=0)
                T = None
            y = yt = None
        if r1 is not None:
            nv = self.sp.nv
            rho = _ein('aeA,nie->niaA', self.Bvv, r1).reshape(
                n, -1, self.naux)
            Ur = cp.matmul(self.sp.U.T[None], rho)            # (n, N, naux)
            rho = None
            M = cp.matmul(Ur, self.Ut.T[None])
            out += M + M.transpose(0, 2, 1)
        return out

    def l1_part(self, L2, t1):
        """2 sum_jb Lad(L2)[ijab] t[jb] - sum_jb Lad(L2)[jiab] t[jb] for
        full L2 (n, o, o, v, v) (the singles of ``lambda_linear``), Lad the
        transposed ladder sum_cd (ca^|db^) L2[ijcd]."""
        no, nv = self.sp.no, self.sp.nv
        th = self.theta.reshape(no, nv, self.naux)
        # sum_jb Lad[i,j,a,b] t[j,b] = sum_A,c B[c,a,A] sum_jd L2[ijcd] th[jdA]
        W1 = _ein('nijcd,jdA->nicA', L2, th)
        W2 = _ein('nijdc,jdA->nicA', L2, th)
        W = 2 * W1 - W2
        W1 = W2 = None
        return _ein('caA,nicA->nia', self.Bvv, W)


class T1Ladder:
    """The canonical ladder with the T1-transformed particle index,

        right:  y[ij,ab] = sum_cd (ac^|bd^) x[ij,cd],
        left:   y[ij,ab] = sum_cd (ca^|db^) x[ij,cd]  (the transpose),

    (a^ = a - sum_m t1[m,a] m), which carries the -t1 (mc|bd) and
    t1 t1 (mc|nd) terms of the sigma vectors (``_ee_sigma`` /
    ``lambda_linear`` with skip 'dress') at the cost of the bare ladder:
    with the MO (ac|bd) on the device (``eom_gpu._vvvv_mo``) that matrix is
    dressed in place once (o v^4; ``mycc._eom_vvvv`` is handed over, so
    the bare one is rebuilt if a canonical EOM needs it later), else the
    AO-direct ladder runs with the T1-transformed virtual coefficients on
    the output (right) or input (left) side.  Both keep the pair symmetry
    (the ladder of X^T is the transpose of that of X)."""

    def __init__(self, mycc, ee):
        from electrolites import eom_gpu as G
        t1 = cp.asarray(ee.t1)
        no, nv = t1.shape
        self.mycc = mycc
        W = G._vvvv_mo(mycc, nv)
        self.W = None
        if W is not None:
            mycc._eom_vvvv = None
            Wv = W.reshape(nv, nv, nv, nv)                     # [c,d,a,b]
            ovvv, ovov = ee.ovvv, ee.ovov
            from electrolites.fastccsd import _avail
            nc = max(1, min(nv, int(.04 * _avail() //
                                    (8 * (no * nv * nv + 2 * nv ** 3)))))
            for c0 in range(0, nv, nc):
                c1 = min(nv, c0 + nc)
                # Z[m,c,b,d] = (mc|bd) - sum_n t[n,b] (mc|nd)
                Z = ovvv[:, c0:c1] - _ein('nb,mcnd->mcbd', t1, ovov[:, c0:c1])
                Wv[c0:c1] -= _ein('ma,mcbd->cdab', t1, Z)
                Z = None
                # - sum_n t[n,b] (nd|ac) = - t[n,b] ovvv[n,d,a,c]
                Wv[c0:c1] -= _ein('nb,ndac->cdab', t1, ovvv[:, :, :, c0:c1])
            self.W = W
        else:
            # AO coefficients; taken to vhfopt's basis per call (the vhfopt
            # is rebuilt when the AO-block cache is dropped)
            mask = mycc.get_frozen_mask()
            mo = cp.asarray(mycc.mo_coeff)[:, cp.asarray(mask)]
            self.cv = mo[:, no:]
            self.cvh = self.cv - mo[:, :no] @ t1

    def _pairs(self, x, f):
        lead = x.shape[:-4]
        no, nv = x.shape[-4], x.shape[-1]
        x = x.reshape((-1, no, no, nv, nv))
        i, j = cp.tril_indices(no)
        xt = x[:, i, j]                                   # (n, npair, v, v)
        y = f(xt.reshape(-1, nv, nv)).reshape(xt.shape)
        xt = None
        out = cp.empty_like(x)
        out[:, i, j] = y
        out[:, j, i] = y.transpose(0, 1, 3, 2)
        return out.reshape(lead + (no, no, nv, nv))

    def _ao(self, x, cin, cout):
        from electrolites import eom_gpu as G
        c = G._ladder_setup(self.mycc).coeff
        cin, cout = c @ cin, c @ cout
        X = _ein('pe,mef,qf->mpq', cin, x, cin)
        Y = G._ladder(self.mycc, X)
        X = None
        return _ein('pa,mpq,qb->mab', cout, Y, cout)

    def right(self, x):
        if self.W is not None:
            return self._pairs(x, lambda m: (m.reshape(len(m), -1) @ self.W)
                               .reshape(m.shape))
        return self._pairs(x, lambda m: self._ao(m, self.cv, self.cvh))

    def left(self, x):
        if self.W is not None:
            return self._pairs(x, lambda m: (m.reshape(len(m), -1) @ self.W.T)
                               .reshape(m.shape))
        return self._pairs(x, lambda m: self._ao(m, self.cvh, self.cv))


class Rings:
    """The uncrossed ring terms of the sigma vectors in a compressed space
    (``_ee_sigma`` / ``lambda_linear`` with skip 'ring'), from ov x N and
    N x N factors built once per space.  As ov x ov matrices (M = U R U^T,
    X the doubles before Hr2 = X + X^T, P[ia,me] = r2[i,m,e,a], E the
    exchange (E Y)[ia,jb] = Y[ib,ja]):

    * right: X = 2 M Wc + P Wx, so U^T X U = 2 R C + U^T (P Vx), with
      C = U^T Wc U and Vx = Wx U; P Vx costs (ov)^2 N per vector instead
      of the o^3 v^3 of the canonical contraction;
    * left (Koch metric G = 2 - E on the output, G^-1 on the input): the
      ring sum_kc (L2[ikac] - L2[ikca]/2) Wv[kc,jb] is M Wv / 2 for
      L2 = G^-1 M, so U^T G(X) U = L C - U^T E(U L K) U / 2 with
      K = U^T Wv, C = K U."""

    def __init__(self, sp, ee=None, imds_l=None):
        no, nv, N, ov = sp.no, sp.nv, sp.N, sp.ov
        U = sp.U
        self.sp = sp
        if ee is not None:
            W = (ee.woVVo * .5 + ee.woVvO).transpose(0, 2, 3, 1)  # m,e,j,b
            W = W.reshape(ov, ov)
            self.C = U.T @ (W @ U)
            W = None
            W = ee.woVvO.transpose(0, 2, 3, 1).reshape(ov, ov)
            self.Vx = -(W @ U)
            W = None
        if imds_l is not None:
            tv = getattr(imds_l, '_tmp_voov', None)
            if tv is None:
                tv = imds_l._tmp_voov = imds_l.wVOov * 2 + imds_l.wvOOv
            W = tv.transpose(2, 3, 1, 0).reshape(ov, ov)          # k,c,j,b
            self.K = (W.T @ U).T                                 # (N, ov)
            W = None
            self.Cl = self.K @ U

    def right(self, R, r2):
        """U^T X U (before symmetrisation) for R (n, N, N), r2 = U R U^T
        (n, o, o, v, v)."""
        sp = self.sp
        no, nv, N = sp.no, sp.nv, sp.N
        out = 2 * cp.matmul(R, self.C)
        for k in range(len(R)):
            # K[i,a,Q] = sum_me r2[i,m,e,a] Vx[me,Q]
            Kx = cp.matmul(r2[k].reshape(no, no * nv, nv).transpose(0, 2, 1),
                           self.Vx)
            out[k] += sp.U.T @ Kx.reshape(-1, N)
            Kx = None
        return out

    def left(self, L):
        """U^T G(X) U (before symmetrisation) for L (n, N, N)."""
        sp = self.sp
        no, nv, N = sp.no, sp.nv, sp.N
        U3 = sp.U.reshape(no, nv, N)
        out = cp.matmul(L, self.Cl)
        for k in range(len(L)):
            H = L[k] @ self.K                                   # (N, ov)
            for i0, i1 in _ichunks(no, no * nv * nv * 8 * 3):
                # Y[i,b,j,a] = (U H)[ib, ja]; G[i,a,Q] = sum_jb Y[ibja] U[jbQ]
                Y = (U3[i0:i1].reshape(-1, N) @ H).reshape(i1 - i0, nv, no, nv)
                Y = cp.ascontiguousarray(Y.transpose(0, 2, 1, 3)).reshape(
                    i1 - i0, no * nv, nv)                       # [i,(j,b),a]
                Gx = cp.matmul(Y.transpose(0, 2, 1), sp.U)        # (i, a, Q)
                Y = None
                out[k] -= .5 * (U3[i0:i1].reshape(-1, N).T @
                                Gx.reshape(-1, N))
                Gx = None
            H = None
        return out


def cupyx_empty_pinned(shape):
    import cupyx
    return cupyx.empty_pinned(shape, dtype=np.float64)


class Ops:
    """Right and left sigma in a compressed space: the canonical kernels on
    the reconstructed doubles for what does not factorise, projected, plus
    the factorised terms: the uncrossed rings (``Rings``, built once per
    space; ``rings=False`` keeps them canonical) and, with ``Bvv`` (DF
    (ae|bf) factors), the ladder (``DFLadder``, built once per space)
    when the cost model prefers it to the AO-direct one; with ``Bov`` too,
    that ladder is the T1-dressed one and replaces the o^3 v^3 dressing
    terms of the sigma.  ``dress``: the canonical ladder is the T1-dressed
    one too (``T1Ladder``), so those terms leave every space."""

    def __init__(self, mycc, imds_ee=None, imds_l=None, Bvv=None, log=None,
                 Bov=None, rings=True, dress=False):
        from electrolites import eom_gpu as G
        self.mycc = mycc
        self.ee = imds_ee if imds_ee is not None else \
            G._make_ee(G._Imds(mycc), mycc)
        h1, _ = G._ee_diag(self.ee, mycc)
        self.h1 = h1
        self.imds_l = imds_l
        self.nsig = 0
        self.dressed = Bvv is not None and Bov is not None
        self.Bvv = dressed_vv(Bvv, Bov, mycc.t1) if self.dressed else Bvv
        # the canonical ladder T1-dressed as well (the dressing terms then
        # leave the sigma whichever ladder a space gets)
        self.t1lad = T1Ladder(mycc, self.ee) if dress else None
        self.log = log
        self._lad = (None, None)
        self.t_ladder = 0.
        self.use_rings = rings
        self._rings = (None, None, None)
        self.t_rings = 0.

    def _costs(self, sp):
        """(AO-direct ladder seconds per vector, flop rate): one timed AO
        ladder on a random vector and one timed GEMM, measured once."""
        if getattr(self, '_t_ao', None) is None:
            from electrolites import eom_gpu as G
            sync = cp.cuda.Device().synchronize
            x = cp.random.random((1, sp.no, sp.no, sp.nv, sp.nv))
            x = x + x.transpose(0, 2, 1, 4, 3)
            if self.t1lad is not None:
                lad = self.t1lad.right
            elif self.ee is not None:
                lad = lambda y: G._ee_ladder(self.ee, self.mycc, y)
            else:                     # left only (right from a checkpoint)
                from electrolites import ccsd_lambda_gpu as LG
                lad = lambda y: LG._ladder_oovv(self.imds_l, self.mycc, y)
            lad(x)                                       # warm-up / setup
            sync()
            t0 = time.perf_counter()
            lad(x)
            sync()
            self._t_ao = time.perf_counter() - t0
            x = None
            a = cp.random.random((8, 1024, 1024))
            cp.matmul(a, a)
            sync()
            t0 = time.perf_counter()
            cp.matmul(a, a)
            sync()
            self._rate = 2 * 8 * 1024 ** 3 / (time.perf_counter() - t0)
            a = None
            if self.log:
                self.log.info('RR ladder: AO-direct %.2f s per vector, GEMM '
                              '%.1f TFLOP/s', self._t_ao, self._rate / 1e12)
        return self._t_ao, self._rate

    def ladder(self, sp):
        """The factorised DF ladder for this space when it is estimated
        cheaper than the AO-direct one (per vector 4 naux N^3 flops plus the
        y build spread over ~10 calls, against the AO ladder and, when
        dressed, the o^3 v^3 dressing contraction it replaces), else None."""
        if self.Bvv is None:
            return None
        if self._lad[0] is sp:
            return self._lad[1]
        t_ao, rate = self._costs(sp)
        naux, N = self.Bvv.shape[2], sp.N
        t_df = (4 * naux * N ** 3 + 2 * naux * N * N * sp.ov / 10) / rate
        t_dress = 2. * sp.no ** 3 * sp.nv ** 3 / rate \
            if self.dressed and self.t1lad is None else 0.
        if t_df > .7 * t_ao + t_dress:
            self._lad = (sp, None)
            return None
        # factorised: the AO integral cache the timing filled is not needed
        self.mycc._fastccsd_eri = None
        cp.get_default_memory_pool().free_all_blocks()
        if self._lad[0] is not sp:
            self._lad = (None, None)
            t0 = time.perf_counter()
            self._lad = (sp, DFLadder(self.Bvv, sp, cp.asarray(self.mycc.t1),
                                      self.log, dressed=self.dressed))
            self.t_ladder += time.perf_counter() - t0
        return self._lad[1]

    def rings(self, sp, side):
        """``Rings`` of this space for 'right' / 'left' (None: canonical)."""
        if not self.use_rings:
            return None
        if self._rings[0] is not sp or self._rings[1] != side:
            self._rings = (None, None, None)
            t0 = time.perf_counter()
            rg = Rings(sp, ee=self.ee if side == 'right' else None,
                       imds_l=self.imds_l if side == 'left' else None)
            cp.cuda.Device().synchronize()
            self.t_rings += time.perf_counter() - t0
            self._rings = (sp, side, rg)
        return self._rings[2]

    def _skip(self, lad, rg):
        dress = self.t1lad is not None if lad is None else lad.dressed
        return (('ring',) if rg is not None else ()) + \
            (('dress',) if dress else ())

    def right(self, sp, V):
        from electrolites import eom_gpu as G
        lad = self.ladder(sp)
        rg = self.rings(sp, 'right')
        skip = self._skip(lad, rg)
        r1, R = sp.unpack(V)
        out = cp.empty_like(V)
        blk = max(1, G._ee_blk(sp.no, sp.nv))
        for p0 in range(0, len(V), blk):
            r2 = expand(sp.U, R[p0:p0 + blk], sp.no, sp.nv)
            h1, h2 = G._ee_sigma(
                self.ee, self.mycc, r1[p0:p0 + blk], r2, skip=skip,
                ladder=False if lad is not None else
                (self.t1lad.right if self.t1lad is not None else True))
            hc = project(sp.U, h2)
            h2 = None
            if rg is not None:
                cp.cuda.Device().synchronize()
                t0 = time.perf_counter()
                zx = rg.right(R[p0:p0 + blk], r2)
                hc += zx + zx.transpose(0, 2, 1)
                zx = None
                cp.cuda.Device().synchronize()
                self.t_rings += time.perf_counter() - t0
            r2 = None
            out[p0:p0 + blk] = sp.pack(h1, hc)
            h1 = hc = None
        if lad is not None:
            # all vectors in one pass over y (streamed from the host for
            # large spaces: 73 GB per pass at Pt EWANIZ's union space)
            cp.cuda.Device().synchronize()
            t0 = time.perf_counter()
            Z = lad.project(R, r1)
            out[:, sp.ov:] += Z[:, sp.tri[0], sp.tri[1]]
            Z = None
            cp.cuda.Device().synchronize()
            self.t_ladder += time.perf_counter() - t0
        self.nsig += len(V)
        return out

    def left(self, sp, V):
        from electrolites import ccsd_lambda_gpu as LG
        from electrolites import eom_gpu as G
        if self.imds_l is None:
            # the Λ intermediates are the memory peak: the DF factors and
            # the ladder wait on the host meanwhile
            Bvv = self.Bvv
            if Bvv is not None:
                self.Bvv = cp.asnumpy(Bvv)
                Bvv = None
            self._lad = (None, None)
            self._rings = (None, None, None)
            cp.get_default_memory_pool().free_all_blocks()
            self.imds_l = LG.make_intermediates(G._Imds(self.mycc))
            if self.Bvv is not None:
                self.Bvv = cp.asarray(self.Bvv)
        lad = self.ladder(sp)
        rg = self.rings(sp, 'left')
        skip = self._skip(lad, rg)
        t1 = cp.asarray(self.mycc.t1)
        l1, Lc = sp.unpack(V)
        out = cp.empty_like(V)
        blk = max(1, G._ee_blk(sp.no, sp.nv))
        for p0 in range(0, len(V), blk):
            l2 = g_inv(expand(sp.U, Lc[p0:p0 + blk], sp.no, sp.nv))
            s1, s2 = LG.lambda_linear(
                self.imds_l, self.mycc, l1[p0:p0 + blk], l2,
                ladder_l1=None if lad is None else
                (lambda L2: lad.l1_part(L2, t1)), skip=skip,
                ladder=self.t1lad.left if lad is None and self.t1lad is not
                None else None)
            l2 = None
            sc = project(sp.U, g_fwd(s2))
            s2 = None
            if rg is not None:
                cp.cuda.Device().synchronize()
                t0 = time.perf_counter()
                zx = rg.left(Lc[p0:p0 + blk])
                sc += zx + zx.transpose(0, 2, 1)
                zx = None
                cp.cuda.Device().synchronize()
                self.t_rings += time.perf_counter() - t0
            out[p0:p0 + blk] = sp.pack(s1, sc)
            s1 = sc = None
        if lad is not None:
            # G commutes with the (dressed, transposed) ladder:
            # P(G Lad(G^-1 X)) = P(Lad X); all vectors in one pass over y
            cp.cuda.Device().synchronize()
            t0 = time.perf_counter()
            Z = lad.project(Lc, trans=True)
            out[:, sp.ov:] += Z[:, sp.tri[0], sp.tri[1]]
            Z = None
            cp.cuda.Device().synchronize()
            self.t_ladder += time.perf_counter() - t0
        self.nsig += len(V)
        return out

    def diag(self, sp):
        return sp.pack(self.h1[None], sp.dd()[None])[0]


def davidson(matvec, x0, diag, nroots, tol_e=1e-7, tol_r=1e-5,
             max_cycle=100, max_space=20, deflate=None, follow=None,
             log=None, tag='RR-EOM'):
    """Non-symmetric Davidson on the device for small (compressed) vectors.
    ``deflate`` (k, dim) orthonormal rows: the solve runs in their
    orthogonal complement (sigma and trial vectors projected); ``follow``
    (dim,): with nroots = 1, the root of largest overlap with it among the
    lowest few is taken instead of the lowest."""
    def orth_out(B):
        if deflate is not None and len(deflate):
            B = B - (B @ deflate.T) @ deflate
        return B

    def mv(B):
        S = matvec(B)
        return orth_out(S)

    V = cp.zeros((0, len(diag)))
    AV = cp.zeros((0, len(diag)))

    def add(B, V, AV):
        B = orth_out(B)
        for _ in range(2):
            if len(V):
                B = B - (B @ V.T) @ V
            keep = []
            for i in range(len(B)):
                for j in keep:
                    B[i] -= (B[j] @ B[i]) * B[j]
                nrm = float(cp.linalg.norm(B[i]))
                if nrm > 1e-8:
                    B[i] /= nrm
                    keep.append(i)
            B = B[keep]
        if not len(B):
            return V, AV, 0
        return cp.vstack([V, B]), cp.vstack([AV, mv(B)]), len(B)

    V, AV, _ = add(cp.asarray(x0), V, AV)
    e_last = None
    conv = np.zeros(nroots, bool)
    for it in range(max_cycle):
        H = cp.asnumpy(V @ AV.T)              # H[i,j] = <V_i|A V_j>
        w, c = np.linalg.eig(H)
        real = np.where(abs(w.imag) < 1e-6 * max(1, abs(w.real).max()))[0]
        w, c = w[real].real, c[:, real].real
        order = np.argsort(w)
        w, c = w[order], c[:, order]
        if follow is not None and nroots == 1:
            X = cp.asarray(c[:, :min(len(w), 6)]).T @ V
            ov = abs(cp.asnumpy(X @ follow)) / cp.asnumpy(
                cp.linalg.norm(X, axis=1))
            k = int(np.argmax(ov))
            sel = [k]
        else:
            sel = list(range(min(nroots, len(w))))
        ws = w[sel]
        cs = cp.asarray(c[:, sel])
        X = cs.T @ V
        R = cs.T @ AV - cp.asarray(ws)[:, None] * X
        xn = cp.linalg.norm(X, axis=1)
        rn = cp.asnumpy(cp.linalg.norm(R, axis=1) / xn)
        de = abs(ws - e_last) if e_last is not None and len(e_last) == \
            len(ws) else np.ones(len(ws))
        e_last = ws
        conv = (de < tol_e) & (rn < tol_r)
        if log:
            log.debug('%s Davidson %d space %d  E %s  |r| %s', tag, it,
                      len(V), ws, rn)
        if conv.all():
            break
        todo = np.where(~conv)[0]
        B = cp.empty((len(todo), len(diag)))
        for i, j in enumerate(todo):
            den = ws[j] - diag
            den = cp.where(abs(den) < 1e-6, 1e-6, den)
            B[i] = R[j] / den / xn[j]
        if len(V) + len(B) > max_space:
            # collapse onto the current Ritz vectors (+ the previous ones)
            keep = cp.asarray(c[:, :min(len(w), max(len(sel), nroots) + 2)])
            if follow is not None and nroots == 1:
                keep = cp.concatenate([cs, keep], axis=1)
            u, s, _ = cp.linalg.svd(keep, full_matrices=False)
            u = u[:, s > 1e-10 * s[0]]
            V, AV = u.T @ V, u.T @ AV
        V, AV, n = add(B, V, AV)
        if not n:
            break
    X = X / xn[:, None]
    return conv, ws, X


def solve_state_specific(mycc, F, ops, guesses, thresh=1e-4,
                         den_thresh=1e-2, max_macro=20, tol_e=1e-6,
                         tol_r=1e-4, log=None, states=None, save=None):
    """TeraChem's state-specific RR-EOM-CCSD (paper II, Algorithm 1): for
    each state, solve in a projector built from its singles and energy,
    rebuild the projector from the new singles, repeat until the energy
    changes by < tol_e; earlier states are deflated (projected into the
    new space and orthogonalised away).  ``guesses``: list of (r1, w).
    Returns a list of dicts (w, r1, r2 full, U, rank, macro iterations)."""
    log = log or logger.new_logger(mycc)
    no, nv = F.no, F.nv
    states = list(states or [])
    cis = [cp.asarray(r).reshape(no, nv) for r, _ in guesses]
    for n, (r1, w) in enumerate(guesses):
        if n < len(states):
            continue
        r1 = cp.asarray(r1).reshape(no, nv)
        r2 = None
        w_old = None
        for k in range(max_macro):
            t0 = time.perf_counter()
            U, g = state_projector(F, r1, w, thresh, den_thresh)
            sp = Space(U, F.dvo, no, nv)
            # the state's current vector, then the other CIS singles: the
            # lowest root of the deflated problem is taken (as TeraChem;
            # following the CIS state instead lost near-degenerate partners
            # when CIS and EOM order the states differently)
            x0 = [sp.pack(r1[None], project(sp.U, r2[None]) if r2 is not None
                          else cp.zeros((1, sp.N, sp.N)))]
            for m, c in enumerate(cis):
                if m != n:
                    x0.append(sp.pack(c[None], cp.zeros((1, sp.N, sp.N))))
            x0 = cp.vstack(x0)
            defl = None
            if states:
                D = cp.vstack([sp.pack(s['r1'][None],
                                       project(sp.U, cp.asarray(s['r2'])[None]))
                               for s in states])
                q, _ = cp.linalg.qr(D.T)
                defl = q.T
            nsig0 = ops.nsig
            # residual tolerance loose in the first macro-iterations, while
            # the projector still moves (TeraChem: start 1e-2, x1e-2)
            tr = max(tol_r, 1e-2 * 1e-1 ** k)
            conv, ws, X = davidson(lambda V: ops.right(sp, V), x0,
                                   ops.diag(sp), 1, tol_e=tol_e, tol_r=tr,
                                   max_cycle=30, max_space=max(12, len(x0)
                                                               + 4),
                                   deflate=defl, log=log, tag=f'SS{n}')
            r1n, Rn = sp.unpack(X)
            nrm = float(cp.linalg.norm(X[0]))
            r1 = r1n[0] / nrm
            r2 = expand(sp.U, Rn / nrm, no, nv)[0]
            wn = float(ws[0])
            ovl = [float(abs(cp.vdot(X[0], d))) for d in defl] \
                if defl is not None else []
            log.info('RR-EOM state %d macro %d  rank %d  w %.10f  dw %.2e  '
                     'sigma %d  %.1f s  overlap with earlier states %s', n, k,
                     sp.N, wn, wn - (w_old if w_old is not None else w),
                     ops.nsig - nsig0, time.perf_counter() - t0,
                     np.round(ovl, 3))
            done = w_old is not None and abs(wn - w_old) < tol_e and \
                tr <= tol_r
            w_old = w = wn
            if done:
                break
        # finished states' doubles wait on the host (o 66, v 288: 2.9 GB
        # each beside the EE intermediates)
        states.append(dict(w=w, r1=r1, r2=cp.asnumpy(r2), U=sp.U, rank=sp.N,
                           macro=k + 1, X=X[0] / nrm, a=sp.a))
        if save is not None:
            save(n, states[-1])
    return states


def cis_guess(mycc, nroots, mf=None):
    """Singles and energies of the lowest CIS (TDA) states in the active
    space (the frozen core dropped), as TeraChem seeds RR-EOM-CCSD."""
    from gpu4pyscf.tdscf import rhf as tdrhf
    from gpu4pyscf.scf import hf as gpu_hf
    mf = mf if mf is not None else mycc._scf
    if not isinstance(mf, gpu_hf.SCF):
        mf = mf.to_gpu()
    td = tdrhf.TDA(mf)
    td.nstates = nroots
    td.verbose = 0
    td.kernel()
    mask = np.asarray(mycc.get_frozen_mask().get()
                      if hasattr(mycc.get_frozen_mask(), 'get')
                      else mycc.get_frozen_mask())
    nocc_all = int((np.asarray(cp.asnumpy(cp.asarray(mf.mo_occ))) > 0).sum())
    occ_act = mask[:nocc_all]
    vir_act = mask[nocc_all:]
    out = []
    for e, (x, _) in zip(np.atleast_1d(cp.asnumpy(cp.asarray(td.e))), td.xy):
        x = cp.asnumpy(cp.asarray(x))[occ_act][:, vir_act]
        out.append((x / np.linalg.norm(x), float(e)))
    return out


def run(mycc, nroots=5, thresh=1e-4, den_thresh=1e-2, int_thresh=1e-2,
        union_thresh=1e-2, auxbasis=None, cc_tol=1e-6, tol_e=1e-7,
        tol_r=1e-5, props=True, verbose=None, mf=None, pre_guess=True,
        df_ladder=True, chk=None, n_extra=2, rings=True, dress=True):
    """The TeraChem RR-EOM-CCSD workflow on a GPU4PySCF CCSD object whose
    SCF is done: RR-CCSD, RR-Λ, state-specific RR-EOM, state-averaged right
    and left RR-EOM, transition properties.  Returns a dict of results and
    timings.  ``rings`` / ``dress``: factorised ring terms / T1-dressed DF
    ladder in the EOM sigma vectors (``Ops``)."""
    from electrolites import eom_gpu as G
    from electrolites import ccsd_lambda_gpu as LG
    log = logger.new_logger(mycc, verbose)
    T = {}
    res = dict(T=T)

    def stamp(k, t0):
        cp.cuda.Device().synchronize()
        T[k] = time.perf_counter() - t0
        log.info('[RR time] %s %.1f s', k, T[k])

    pool = cp.get_default_memory_pool()
    pool.set_limit(fraction=1.0)
    with cp.cuda.using_allocator(pool.malloc):
        t0 = time.perf_counter()
        F = Factors(mycc, auxbasis, int_thresh)
        stamp('factors', t0)
        log.info('RR factors: naux %d, Cholesky-reduced %d', F.naux, F.K)
        t0 = time.perf_counter()
        U0, _ = ground_projector(F, thresh, den_thresh)
        sp0 = Space(U0, F.dvo, F.no, F.nv)
        res['rank_cc'] = sp0.N
        log.info('RR-CCSD rank %d (ov %d)', sp0.N, sp0.ov)
        mycc.e_hf = mycc.get_e_hf()
        import os
        ck = (lambda name: os.path.join(chk, name)) if chk else None
        if ck and os.path.exists(ck('rr_ccsd.npz')):
            z = np.load(ck('rr_ccsd.npz'))
            sp0 = Space.from_rotated(z['U'], z['a'], F.no, F.nv)
            t1, Tc, ecc = cp.asarray(z['t1']), cp.asarray(z['T']), \
                float(z['e_corr'])
            mycc.t1, mycc.e_corr = t1, ecc
            mycc.t2 = expand(sp0.U, Tc[None], F.no, F.nv)[0]
            log.info('RR-CCSD from %s: E_corr %.12f', ck('rr_ccsd.npz'), ecc)
        else:
            conv, ecc, t1, Tc = rr_ccsd(mycc, sp0, tol=cc_tol,
                                        tolnormt=cc_tol, log=log)
            if ck:
                np.savez(ck('rr_ccsd.npz'), U=cp.asnumpy(sp0.U),
                         a=cp.asnumpy(sp0.a),
                         t1=cp.asnumpy(t1), T=cp.asnumpy(Tc), e_corr=ecc)
        res['e_corr'] = ecc
        stamp('ccsd', t0)
        t0 = time.perf_counter()
        Bvv = None
        if ck and os.path.exists(ck('rr_lambda.npz')):
            z = np.load(ck('rr_lambda.npz'))
            mycc.l1 = cp.asarray(z['l1'])
            mycc.l2 = g_inv(expand(sp0.U, cp.asarray(z['L'])[None], F.no,
                                   F.nv))[0]
        else:
            # the Λ intermediates are the memory peak (o 66, v 288: 44 GB
            # plus temporaries): the factors wait on the host meanwhile
            F.offload()
            pool.free_all_blocks()
            box = []

            def get_bvv():
                box.append(df_vv(F) if df_ladder else None)
                return box[0]
            _, l1c, Lcc = rr_lambda(mycc, sp0, tol=cc_tol, log=log,
                                    Bvv=get_bvv)
            Bvv = box[0] if box else None
            F.onload()
            if ck:
                np.savez(ck('rr_lambda.npz'), l1=cp.asnumpy(l1c),
                         L=cp.asnumpy(Lcc))
            l1c = Lcc = None
        if Bvv is None and df_ladder:
            Bvv = df_vv(F)
        pool.free_all_blocks()
        stamp('lambda', t0)
        t0 = time.perf_counter()
        # two CIS states more than wanted for the pre-pass space: with
        # exactly nroots, Pt EWANIZ's 3.29 eV state (a near-degenerate
        # partner) was missing from it and the state-specific solve of the
        # fifth state went to 3.53 eV
        guesses = cis_guess(mycc, nroots + (n_extra if pre_guess else 0), mf)
        res['cis'] = [w for _, w in guesses]
        stamp('cis', t0)
        t0 = time.perf_counter()
        ops = Ops(mycc, Bvv=Bvv, log=log, rings=rings,
                  Bov=F.Bov if dress else None, dress=dress)
        Bvv = None
        stamp('ee_imds', t0)
        all_ss = bool(ck) and all(os.path.exists(ck(f'rr_ss{n}.npz'))
                                  for n in range(nroots))
        if all_ss:
            res['nsig_pre'] = 0
        elif pre_guess and ck and os.path.exists(ck('rr_pre.npz')):
            z = np.load(ck('rr_pre.npz'))
            guesses = [(r, float(w)) for r, w in zip(z['r1'], z['w'])]
            res['nsig_pre'] = 0
            log.info('RR-EOM pre-pass from checkpoint')
        elif pre_guess:
            # paper II: one projector from all the CIS states, the lowest
            # roots in it (loosely) seed the state-specific solves with
            # EOM-like singles in energy order
            t0 = time.perf_counter()
            Ps = [state_projector(F, r, w, thresh, den_thresh)[0]
                  for r, w in guesses]
            Uu, _ = union_projector(Ps, union_thresh)
            spp = Space(Uu, F.dvo, F.no, F.nv)
            Ps = Uu = None
            x0 = cp.vstack([spp.pack(cp.asarray(r).reshape(1, F.no, F.nv),
                                     cp.zeros((1, spp.N, spp.N)))
                            for r, _ in guesses])
            n0 = ops.nsig
            _, wp, Xp = davidson(lambda V: ops.right(spp, V), x0,
                                 ops.diag(spp), nroots + 1, tol_e=1e-5,
                                 tol_r=1e-3, max_space=4 * (nroots + 1)
                                 + len(x0), log=log, tag='pre')
            r1p, _ = spp.unpack(Xp)
            guesses = [(cp.asnumpy(r1p[k] / cp.linalg.norm(Xp[k])),
                        float(wp[k])) for k in range(nroots)]
            res['nsig_pre'] = ops.nsig - n0
            res['pre_rank'] = spp.N
            spp = None
            log.info('RR-EOM pre-pass rank %d  w (eV) %s', res['pre_rank'],
                     wp * 27.211386245988)
            if ck:
                np.savez(ck('rr_pre.npz'), r1=np.asarray([g[0] for g in
                                                          guesses]),
                         w=np.asarray([g[1] for g in guesses]))
            stamp('eom_pre', t0)
        t0 = time.perf_counter()
        done = []
        while ck and os.path.exists(ck(f'rr_ss{len(done)}.npz')):
            z = np.load(ck(f'rr_ss{len(done)}.npz'))
            sps = Space.from_rotated(z['U'], z['a'], F.no, F.nv)
            r1s, Rs = sps.unpack(cp.asarray(z['X'])[None])
            done.append(dict(w=float(z['w']), r1=r1s[0],
                             r2=cp.asnumpy(expand(sps.U, Rs, F.no, F.nv)[0]),
                             U=sps.U,
                             rank=sps.N, macro=int(z['macro'])))
            log.info('RR-EOM state %d from checkpoint: w %.10f',
                     len(done) - 1, done[-1]['w'])

        def save(n, st):
            if ck:
                np.savez(ck(f'rr_ss{n}.npz'), U=cp.asnumpy(st['U']),
                         a=cp.asnumpy(st['a']), X=cp.asnumpy(st['X']),
                         w=st['w'], macro=st['macro'])
        ss = solve_state_specific(mycc, F, ops, guesses[:nroots], thresh,
                                  den_thresh, log=log, states=done,
                                  save=save)
        res['ss_w'] = [s['w'] for s in ss]
        res['ss_rank'] = [s['rank'] for s in ss]
        res['ss_macro'] = [s['macro'] for s in ss]
        res['nsig_ss'] = ops.nsig - res.get('nsig_pre', 0)
        stamp('eom_ss', t0)
        t0 = time.perf_counter()
        n0 = ops.nsig
        if ck and os.path.exists(ck('rr_sa_right.npz')):
            z = np.load(ck('rr_sa_right.npz'))
            sp = Space.from_rotated(z['U'], z['a'], F.no, F.nv)
            w, X, conv = z['w'], cp.asarray(z['X']), z['conv']
            log.info('RR-EOM state-averaged right from checkpoint')
        else:
            Uu, _ = union_projector([s['U'] for s in ss], union_thresh)
            sp = Space(Uu, F.dvo, F.no, F.nv)
            Uu = None
            x0 = cp.vstack([sp.pack(s['r1'][None],
                                    project(sp.U, cp.asarray(s['r2'])[None]))
                            for s in ss])
            conv, w, X = davidson(lambda V: ops.right(sp, V), x0,
                                  ops.diag(sp), nroots, tol_e=tol_e,
                                  tol_r=tol_r, max_space=4 * nroots, log=log,
                                  tag='SA-right')
            if ck:
                np.savez(ck('rr_sa_right.npz'), U=cp.asnumpy(sp.U),
                         a=cp.asnumpy(sp.a), w=w, X=cp.asnumpy(X), conv=conv)
        res['rank_union'] = sp.N
        log.info('RR-EOM union rank %d', sp.N)
        res['w'] = w
        res['conv_right'] = conv
        res['nsig_right'] = ops.nsig - n0
        stamp('eom_right', t0)
        log.info('RR-EOM state-averaged right (eV) %s', w * 27.211386245988)
        t0 = time.perf_counter()
        # the left operator builds the Λ intermediates (o 66, v 288: 44 GB
        # plus temporaries): drop the EE ones, fastccsd's AO integral cache
        # (filled by the AO-ladder timing), and park what waits on the host
        ops.ee = None
        mycc._fastccsd_vhfopt = mycc._fastccsd_eri = None
        F.offload()
        mycc.l2 = cp.asnumpy(mycc.l2)
        ss = None
        pool.free_all_blocks()
        n0 = ops.nsig
        convl, wl, XL = davidson(lambda V: ops.left(sp, V), X, ops.diag(sp),
                                 nroots,
                                 tol_e=tol_e, tol_r=tol_r,
                                 max_space=4 * nroots, log=log, tag='SA-left')
        res['w_left'] = wl
        res['conv_left'] = convl
        res['nsig_left'] = ops.nsig - n0
        stamp('eom_left', t0)
        if props:
            t0 = time.perf_counter()
            order = [int(np.argmin(abs(wl - x))) for x in w]
            no, nv = F.no, F.nv
            r1, R = sp.unpack(X)
            l1, Lc = sp.unpack(XL[order])
            rv, lv = [], []
            for k in range(nroots):
                r2 = expand(sp.U, R[k:k + 1], no, nv)
                rv.append(cp.asnumpy(G._pack_singlet(r1[k:k + 1], r2)[0]))
                l2 = g_inv(expand(sp.U, Lc[k:k + 1], no, nv))
                lv.append(cp.asnumpy(G._pack_singlet(l1[k:k + 1], l2)[0]))
            ops.imds_l = None
            p = G.transition_properties(mycc, w, rv, lv, mycc.l1, mycc.l2)
            res['props'] = p
            stamp('props', t0)
        res['t_ladder'] = ops.t_ladder
        res['t_rings'] = ops.t_rings
    return res

