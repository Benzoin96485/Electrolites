"""Write electrolites/kernels/cuda/mygrid/d2w_fused.cu from GPU4PySCF's
lib/gdft/gen_grids.cu (catalogue B9).

GPU4PySCF's two second-derivative kernels of the Becke partition weights
store ``d2w[G, H, 3, 3, grid]`` -- natm^2 * 9 doubles a grid point -- which
the Hessian then contracts with one vector over the grid.  Here each kernel
body becomes a ``__device__`` function returning its point's 3x3 block
instead of storing it, and electrolites/fastgridresp.py's wrappers contract
it on the fly.  The arithmetic is lifted verbatim; only the signature, the
early returns and the nine stores change.

    python codegen/gen_d2w_fused.py /path/to/gpu4pyscf/lib/gdft/gen_grids.cu
"""
import re
import sys

src = open(sys.argv[1]).read()
out = sys.argv[2] if len(sys.argv) > 2 else \
    'electrolites/kernels/cuda/mygrid/d2w_fused.cu'


def between(a, b):
    i = src.index(a)
    j = src.index(b, i)
    return src[i:j]


licence = src[:src.index('*/') + 2]
enum = between('enum class GridPartitionScheme', 'static inline GridPartitionScheme')
helpers1 = between('__device__ double3 operator+',
                   'template <bool if_radii_adjust, GridPartitionScheme scheme>\n'
                   '__global__\nvoid GDFTgrid_weight_derivative_kernel')
helpers2 = between('typedef struct {\n    double3 x;',
                   'template <bool if_radii_adjust, GridPartitionScheme scheme>\n'
                   '__global__\nvoid GDFTgrid_weight_second_derivative_offdiagonal_kernel')
offd = between('template <bool if_radii_adjust, GridPartitionScheme scheme>\n'
               '__global__\nvoid GDFTgrid_weight_second_derivative_offdiagonal_kernel',
               'template <bool if_radii_adjust, GridPartitionScheme scheme>\n'
               '__global__\nvoid GDFTgrid_weight_second_derivative_diagonal_kernel')
diag = between('template <bool if_radii_adjust, GridPartitionScheme scheme>\n'
               '__global__\nvoid GDFTgrid_weight_second_derivative_diagonal_kernel',
               'int GDFTbecke_partition_weight_second_derivative')
# up to the next top-level definition: the diagonal kernel is followed by
# other kernels and the host wrappers
_k = diag.index('__global__')
_ends = [i for i in (diag.find('\ntemplate', _k), diag.find('\n__global__', _k + 10),
                     diag.find('\n__host__', _k)) if i > 0]
diag = diag[:min(_ends)]
diag = diag[:diag.rindex('}') + 1]


def to_device(body, old_name, new_name, var):
    body = body.replace('__global__\nvoid ' + old_name +
                        '(double* __restrict__ d2w_dG1dG2,',
                        '__device__ __forceinline__\nbool ' + new_name +
                        '(double9* __restrict__ d2w_out,')
    body = body.replace('return;', 'return false;')
    stores = re.compile(r'(\s*d2w_dG1dG2\[[^\n]*\] = ' + var +
                        r'\.\w\.\w;)+')
    body, n = stores.subn('\n    *d2w_out = ' + var + ';\n    return true;',
                          body)
    assert n == 1, (old_name, n)
    return body


offd = to_device(offd, 'GDFTgrid_weight_second_derivative_offdiagonal_kernel',
                 'd2w_offdiag_point', 'd2wi_dGdH')
diag = to_device(diag, 'GDFTgrid_weight_second_derivative_diagonal_kernel',
                 'd2w_diag_point', 'd2wi_dG2')

with open(out, 'w') as f:
    f.write(licence + '\n')
    f.write('/* GENERATED by codegen/gen_d2w_fused.py from GPU4PySCF\'s\n'
            ' * lib/gdft/gen_grids.cu -- do not edit.  The two second-derivative\n'
            ' * kernels as __device__ functions returning their point\'s 3x3 block;\n'
            ' * the contraction wrappers are in d2w_fused_wrappers.cu. */\n\n')
    # NVRTC has no <math.h>
    f.write('#ifndef NAN\n#define NAN __longlong_as_double(0x7ff8000000000000ULL)\n'
            '#endif\n\n')
    f.write(enum + '\n')
    f.write(helpers1 + '\n' + helpers2 + '\n' + offd + '\n' + diag + '\n')
print('wrote', out)
